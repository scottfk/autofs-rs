#!/usr/bin/env python3
# gen-tables.py - extract the flex scanner and bison parser tables from the reference build's generated C into Rust
#
# 20261126 - Created by Claude (claude.ai, Anthropic) - scottfk
# 20261126 - Fixed-length trailing context trims, rustfmt::skip on the modules - Claude - scottfk
#
# Usage: tools/gen-tables.py [REFERENCE_DIR]
#
# Reads daemon/master_tok.c, daemon/master_parse.tab.c, lib/nss_tok.c,
# lib/nss_parse.tab.c, modules/amd_tok.c and modules/amd_parse.tab.c, which
# flex 2.6.4 and bison 3.8.2 generate from upstream's .l and .y files when the
# reference is built, and writes crates/automount/src/tables/*.rs: the tables, the
# constants the skeletons hard-code, the start states and the token numbers.
# The skeletons themselves are ported once, in crates/automount/src/libautofs/flex.rs
# and bison.rs; the rule actions are ported by hand next to the grammars.

import os
import re
import sys

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ref = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'autofs')
out = os.path.join(here, 'crates', 'automount', 'src', 'tables')

HEADER = """// @generated by tools/gen-tables.py from the reference build's {src}
// ({tool}); don't edit. Regenerate after a reference bump.
"""


def read(rel):
    with open(os.path.join(ref, rel), encoding='latin-1') as f:
        return f.read()


def array(text, name):
    m = re.search(r'static const (?:flex_int16_t|flex_int32_t|YY_CHAR|yytype_int8|yytype_uint8|yytype_int16|yytype_uint16) '
                  + re.escape(name) + r'\[(\d*)\]\s*=\s*\{(.*?)\}\s*;', text, re.S)
    if not m:
        return None
    body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
    vals = [int(v) for v in re.findall(r'-?\d+', body)]
    assert not m.group(1) or len(vals) == int(m.group(1)), name
    return vals


def define(text, name):
    m = re.search(r'#\s*define ' + re.escape(name) + r'\s+\(?(-?\d+)\)?', text)
    assert m, name
    return int(m.group(1))


def rust_array(name, vals):
    lo, hi = min(vals), max(vals)
    ty = 'i16' if -32768 <= lo and hi <= 32767 else 'i32'
    lines = []
    for i in range(0, len(vals), 16):
        lines.append('    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',')
    return f'pub static {name}: [{ty}; {len(vals)}] = [\n' + '\n'.join(lines) + '\n];\n'


def flex(src, mod):
    t = read(src)
    s = [HEADER.format(src=src, tool='flex 2.6.4'), '\n']
    reject = 'yy_acclist' in t
    s.append(f'pub const REJECT: bool = {"true" if reject else "false"};\n')
    s.append(f'pub const USES_BOL: bool = {"true" if "yy_current_state += YY_AT_BOL()" in t else "false"};\n')
    s.append(f'pub const NUM_RULES: i32 = {define(t, "YY_NUM_RULES")};\n')
    s.append(f'pub const END_OF_BUFFER: i32 = {define(t, "YY_END_OF_BUFFER")};\n')
    # The constants the skeleton hard-codes.
    m = re.search(r'if \( yy_current_state >= (\d+) \)', t)
    s.append(f'pub const META_LIMIT: i32 = {m.group(1)};\n')
    m = re.search(r'while \( yy_base\[yy_current_state\] != (\d+) \);', t)
    s.append(f'pub const JAM_BASE: i32 = {m.group(1)};\n')
    m = re.search(r'YY_CHAR yy_c = \(\*yy_cp \? yy_ec\[YY_SC_TO_UI\(\*yy_cp\)\] : (\d+)\);', t)
    s.append(f'pub const NUL_EC: i32 = {m.group(1)};\n')
    m = re.search(r'yy_is_jam = \(yy_current_state == (\d+)\);', t)
    s.append(f'pub const JAM_STATE: i32 = {m.group(1)};\n')
    if reject:
        s.append(f'pub const TRAILING_MASK: i32 = {int(re.search(r"#define YY_TRAILING_MASK (0x[0-9a-f]+)", t).group(1), 16)};\n')
        s.append(f'pub const TRAILING_HEAD_MASK: i32 = '
                 f'{int(re.search(r"#define YY_TRAILING_HEAD_MASK (0x[0-9a-f]+)", t).group(1), 16)};\n')
    else:
        s.append('pub const TRAILING_MASK: i32 = 0;\npub const TRAILING_HEAD_MASK: i32 = 0;\n')
    # Start states, in the order flex numbers them.
    for name, num in re.findall(r'^#define ([A-Z_]+) (\d+)$', t[t.index('#define INITIAL 0'):], re.M):
        if name.startswith('YY'):
            break
        s.append(f'pub const {name}: i32 = {num};\n')
    # Rules whose trailing context or head has a fixed length: flex trims
    # yytext in the rule's own case (`yy_cp -= n` or `yy_cp = yy_bp + n`).
    trail = []
    for m in re.finditer(r'case (\d+):\n(?:/\*[^\n]*\*/\n)?\*yy_cp = \(yy_hold_char\);[^\n]*\n'
                         r'(?:YY_LINENO_REWIND_TO[^\n]*\n)?\(yy_c_buf_p\) = yy_cp (-= (\d+)|= yy_bp \+ (\d+));', t):
        if m.group(3):
            trail.append((int(m.group(1)), 0, int(m.group(3))))
        else:
            trail.append((int(m.group(1)), 1, int(m.group(4))))
    s.append('/// (rule, 0 = drop the last n bytes / 1 = keep the first n, n).\n')
    s.append('pub static TRAIL: [(i32, i32, i32); %d] = [%s];\n' % (len(trail), ', '.join('(%d, %d, %d)' % x for x in trail)))
    s.append('\n')
    for name in ['yy_acclist', 'yy_accept', 'yy_ec', 'yy_meta', 'yy_base', 'yy_def', 'yy_nxt', 'yy_chk']:
        vals = array(t, name)
        if vals is None:
            assert name == 'yy_acclist'
            vals = [0]
        s.append(rust_array(name.upper(), vals))
    s.append('\npub static TABLES: crate::libautofs::flex::Tables = crate::libautofs::flex::Tables {\n'
             '    reject: REJECT,\n    uses_bol: USES_BOL,\n    end_of_buffer: END_OF_BUFFER,\n'
             '    meta_limit: META_LIMIT,\n    jam_base: JAM_BASE,\n    nul_ec: NUL_EC,\n    jam_state: JAM_STATE,\n'
             '    trailing_mask: TRAILING_MASK,\n    trailing_head_mask: TRAILING_HEAD_MASK,\n'
             '    trail: &TRAIL,\n'
             '    acclist: &YY_ACCLIST,\n    accept: &YY_ACCEPT,\n    ec: &YY_EC,\n    meta: &YY_META,\n'
             '    base: &YY_BASE,\n    def: &YY_DEF,\n    nxt: &YY_NXT,\n    chk: &YY_CHK,\n};\n')
    with open(os.path.join(out, mod + '.rs'), 'w') as f:
        f.write(''.join(s))


def bison(src, mod):
    t = read(src)
    s = [HEADER.format(src=src, tool='bison 3.8.2'), '\n']
    for name in ['YYFINAL', 'YYLAST', 'YYNTOKENS', 'YYNNTS', 'YYNRULES', 'YYNSTATES', 'YYMAXUTOK',
                 'YYPACT_NINF', 'YYTABLE_NINF', 'YYINITDEPTH', 'YYMAXDEPTH']:
        s.append(f'pub const {name}: i32 = {define(t, name)};\n')
    m = re.search(r'#define yytable_value_is_error\(Yyn\) \\\s*(.*)\n', t)
    always_ok = m.group(1).strip() == '0'
    s.append(f'pub const TABLE_ERROR_NEVER: bool = {"true" if always_ok else "false"};\n')
    # Token numbers.
    enum = re.search(r'enum yytokentype\s*\{(.*?)\}\s*;', read(src.replace('.c', '.h')), re.S).group(1)
    for name, num in re.findall(r'(\w+) = (-?\d+)', enum):
        if name in ('YYEMPTY', 'YYEOF', 'YYerror', 'YYUNDEF'):
            continue
        s.append(f'pub const {name}: i32 = {num};\n')
    s.append('\n')
    for name in ['yytranslate', 'yypact', 'yydefact', 'yypgoto', 'yydefgoto', 'yytable', 'yycheck', 'yyr1', 'yyr2']:
        s.append(rust_array(name.upper(), array(t, name)))
    s.append('\npub static TABLES: crate::libautofs::bison::Tables = crate::libautofs::bison::Tables {\n'
             '    yyfinal: YYFINAL,\n    yylast: YYLAST,\n    yyntokens: YYNTOKENS,\n    yymaxutok: YYMAXUTOK,\n'
             '    yypact_ninf: YYPACT_NINF,\n    yytable_ninf: YYTABLE_NINF,\n    table_error_never: TABLE_ERROR_NEVER,\n'
             '    yyinitdepth: YYINITDEPTH,\n    yymaxdepth: YYMAXDEPTH,\n'
             '    translate: &YYTRANSLATE,\n    pact: &YYPACT,\n    defact: &YYDEFACT,\n    pgoto: &YYPGOTO,\n'
             '    defgoto: &YYDEFGOTO,\n    table: &YYTABLE,\n    check: &YYCHECK,\n    r1: &YYR1,\n    r2: &YYR2,\n};\n')
    with open(os.path.join(out, mod + '.rs'), 'w') as f:
        f.write(''.join(s))


os.makedirs(out, exist_ok=True)
flex('daemon/master_tok.c', 'master_tok')
bison('daemon/master_parse.tab.c', 'master_parse')
flex('lib/nss_tok.c', 'nss_tok')
bison('lib/nss_parse.tab.c', 'nss_parse')
flex('modules/amd_tok.c', 'amd_tok')
bison('modules/amd_parse.tab.c', 'amd_parse')
with open(os.path.join(out, 'mod.rs'), 'w') as f:
    f.write('// @generated by tools/gen-tables.py; don\'t edit.\n\n'
            '//! The flex and bison tables of upstream\'s three grammars.\n\n'
            '#![allow(dead_code, clippy::all)]\n\n'
            '#[rustfmt::skip]\npub mod amd_parse;\n#[rustfmt::skip]\npub mod amd_tok;\n'
            '#[rustfmt::skip]\npub mod master_parse;\n#[rustfmt::skip]\npub mod master_tok;\n'
            '#[rustfmt::skip]\npub mod nss_parse;\n#[rustfmt::skip]\npub mod nss_tok;\n')
print('wrote', out)
